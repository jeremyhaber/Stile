#!/usr/bin/env bash
# Build Stile.app (release), bundle the web UI and the extension folder, sign, zip to mac/dist/Stile.zip.
# Set UNIVERSAL=1 for an arm64+x86_64 binary. Set VERSION=x.y.z to override the version string.
# Signing: SIGN_IDENTITY="<name>" picks a code-signing certificate; unset, "Stile Developer" (the release certificate,
# self-signed, need not be trusted) is used if it is in the keychain, else the first valid one, else ad-hoc. Releases must
# always be signed with the same certificate: macOS ties the Accessibility and Screen Recording grants to it, so a stable
# certificate keeps them across updates and a different one makes every user grant them again.
set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
EXT="$(cd "$HERE/../extension" && pwd)"
DIST="$HERE/dist"
APP="$DIST/Stile.app"
VERSION="${VERSION:-1.0.0}"
BUILD="${GITHUB_RUN_NUMBER:-1}"

# Files that must exist in extension/ (the web UI copied to Contents/Resources/web is every top-level
# *.js, *.css, *.html and *.png plus icons/, so new UI files are picked up automatically).
WEB_FILES=(sidepanel.html sidepanel.css sidepanel.js shared.js icons.js boost-view.js boost.css bridge-shim.js)

missing=0
for f in "${WEB_FILES[@]}"; do
  if [ ! -f "$EXT/$f" ]; then
    echo "error: required web UI file missing: extension/$f" >&2
    missing=1
  fi
done
if [ "$missing" -ne 0 ]; then
  echo "error: cannot assemble Stile.app without the files above" >&2
  exit 1
fi

cd "$HERE"
ARCHS=()
if [ "${UNIVERSAL:-0}" = "1" ]; then ARCHS=(--arch arm64 --arch x86_64); fi
swift build -c release ${ARCHS[@]+"${ARCHS[@]}"}
BIN_DIR="$(swift build -c release ${ARCHS[@]+"${ARCHS[@]}"} --show-bin-path)"
if [ ! -x "$BIN_DIR/StileApp" ]; then
  echo "error: built executable not found at $BIN_DIR/StileApp" >&2
  exit 1
fi

rm -rf "$APP" "$DIST/Stile.zip"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources/web"
cp "$BIN_DIR/StileApp" "$APP/Contents/MacOS/StileApp"
sed -e "s/__VERSION__/$VERSION/g" -e "s/__BUILD__/$BUILD/g" "$HERE/Resources/Info.plist" > "$APP/Contents/Info.plist"
# App icon (iconset generated by tools/gen-mac-icon.js).
if [ -d "$HERE/Resources/AppIcon.iconset" ]; then
  iconutil -c icns "$HERE/Resources/AppIcon.iconset" -o "$APP/Contents/Resources/AppIcon.icns"
fi
# Web UI for the sidebar's web view: the whole extension folder (subfolders included), via copy-web.sh.
bash "$HERE/copy-web.sh" "$EXT" "$APP/Contents/Resources/web"
# The whole extension folder, so the user can "Load unpacked" a copy that always matches this app.
rm -rf "$APP/Contents/Resources/extension"
cp -R "$EXT" "$APP/Contents/Resources/extension"
printf 'APPL????' > "$APP/Contents/PkgInfo"

IDENTITY="${SIGN_IDENTITY:-}"
if [ -z "$IDENTITY" ] && security find-identity -p codesigning 2>/dev/null | grep -q '"Stile Developer"'; then
  IDENTITY="Stile Developer"
fi
if [ -z "$IDENTITY" ]; then
  IDENTITY="$(security find-identity -v -p codesigning 2>/dev/null | awk -F'"' '/^ *[0-9]+\)/ { print $2; exit }')"
fi
if [ -n "$IDENTITY" ]; then
  echo "Signing with: $IDENTITY"
  codesign --force --deep -s "$IDENTITY" "$APP"
else
  echo "Signing ad-hoc (no code-signing certificate found; Accessibility must be re-granted after each build)"
  codesign --force --deep -s - "$APP"
fi
codesign --verify --deep --strict "$APP"
# The bundle was replaced in place: have Launch Services re-read it (icon shown in System Settings, Finder).
touch "$APP"
LSREG=/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister
[ -x "$LSREG" ] && "$LSREG" -f "$APP" || true

(cd "$DIST" && ditto -c -k --keepParent Stile.app Stile.zip)
echo "Built $APP"
echo "Zip:   $DIST/Stile.zip"
